"""The shipper's lane scorecard (SYNTHETIC demo data).

Public 10-Ks do not report how often a carrier accepts one shipper's tenders, its on-time rate on a lane,
its rate per mile or its claims ratio. A real shipper reads those from its own TMS. LaneRoom ships a
clearly labelled synthetic scorecard (``data/scorecard/shipper_scorecard_synthetic.csv``, generated by
``scripts/make_scorecard.py``) with one row per lane, carrier and quarter of 2025.

Every row becomes an evidence item with a row id (``S07``) so claims can cite it and the Verifier can
check the numbers against the row, exactly like a 10-K page.
"""
from __future__ import annotations

import csv
import re
from functools import lru_cache

from . import config

# How a request names a lane. Checked in order; the first match wins.
LANE_PATTERNS = (
    ("PEAK-NAT", re.compile(r"\b(peak|surge|holiday|q4 capacity|seasonal)\b", re.I)),
    ("LTL-NAT", re.compile(r"\b(ltl|less[- ]than[- ]truckload)\b", re.I)),
    ("CHI-LAX", re.compile(r"\b(chicago|los angeles|\bla\b|intermodal|chi\W+lax)\b", re.I)),
    ("DAL-ATL", re.compile(r"\b(dallas|atlanta|dal\W+atl|dry van)\b", re.I)),
)
DEFAULT_LANE = "DAL-ATL"
SOURCE_LABEL = "Synthetic shipper scorecard"


@lru_cache(maxsize=1)
def load_rows() -> tuple[dict, ...]:
    out = []
    with config.SCORECARD_PATH.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            for k in ("tenders_offered", "tenders_accepted"):
                r[k] = int(r[k])
            for k in ("acceptance_pct", "on_time_pct", "rate_per_mile", "claims_pct"):
                r[k] = float(r[k])
            out.append(r)
    return tuple(out)


def lanes() -> dict[str, dict]:
    """lane_id -> {"lane", "mode", "carriers"} in file order."""
    out: dict[str, dict] = {}
    for r in load_rows():
        lane = out.setdefault(r["lane_id"], {"lane_id": r["lane_id"], "lane": r["lane"], "mode": r["mode"], "carriers": []})
        if r["carrier"] not in lane["carriers"]:
            lane["carriers"].append(r["carrier"])
    return out


def detect_lane(question: str) -> str:
    for lane_id, pat in LANE_PATTERNS:
        if pat.search(question or ""):
            return lane_id
    return DEFAULT_LANE


def lane_rows(lane_id: str, carrier: str | None = None) -> list[dict]:
    return [r for r in load_rows() if r["lane_id"] == lane_id and (carrier is None or r["carrier"] == carrier)]


def row_text(r: dict) -> str:
    """One scorecard row as a sentence the agents can quote and the Verifier can check."""
    return (f"{r['lane']} ({r['mode']}), {r['period']}: {r['carrier']} accepted {r['tenders_accepted']:,} of "
            f"{r['tenders_offered']:,} tenders ({r['acceptance_pct']}% acceptance), on-time {r['on_time_pct']}%, "
            f"rate ${r['rate_per_mile']:.2f} per mile, claims {r['claims_pct']}%.")


def summary(lane_id: str, carrier: str) -> dict | None:
    """Full-year 2025 figures for one carrier on one lane (volume-weighted)."""
    rows = lane_rows(lane_id, carrier)
    if not rows:
        return None
    off = sum(r["tenders_offered"] for r in rows)
    acc = sum(r["tenders_accepted"] for r in rows)
    w = lambda k: sum(r[k] * r["tenders_offered"] for r in rows) / off  # noqa: E731
    q4 = next((r for r in rows if r["period"].startswith("Q4")), rows[-1])
    return {
        "lane_id": lane_id, "lane": rows[0]["lane"], "mode": rows[0]["mode"], "carrier": carrier,
        "tenders_offered": off, "tenders_accepted": acc, "acceptance_pct": round(acc / off * 100, 1),
        "on_time_pct": round(w("on_time_pct"), 1), "rate_per_mile": round(w("rate_per_mile"), 2),
        "claims_pct": round(w("claims_pct"), 2), "q4_acceptance_pct": q4["acceptance_pct"],
        "rows": [r["row_id"] for r in rows], "q4_row": q4["row_id"],
    }


def evidence(lane_id: str, carriers: list[str] | None = None) -> list[dict]:
    """Scorecard rows for a lane in the same shape as filing evidence (page -> row id)."""
    out = []
    for r in lane_rows(lane_id):
        if carriers and r["carrier"] not in carriers:
            continue
        out.append({
            "chunk_id": f"scorecard-{r['row_id']}", "company": r["carrier"], "page": 0, "row": r["row_id"],
            "item": "Scorecard", "item_title": f"{r['lane']} · {r['period']}", "header": f"{SOURCE_LABEL} row {r['row_id']}",
            "text": row_text(r), "score": 1.0, "topic": "scorecard", "source": "scorecard", "synthetic": True,
        })
    return out
